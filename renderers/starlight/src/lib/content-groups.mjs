// Sidebar groups of a content section (front matter `group:` of the pages, used by How-to).
// Same rules as renderers/lhtml/build.py (inherited_groups, sort_key):
//  - a page without `group:` takes the group of the page before it (in `order`), with a warning;
//  - groups are ranked by the smallest `order` of their pages, pages inside a group by `order`,
//    then by file name: the pages of a group are contiguous, and previous / next (which
//    Starlight derives from the sidebar) follow the same order as the menu.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const CONTENT = path.resolve(process.env.CGP_CONTENT_DIR ?? path.join(HERE, '..', '..', '..', '..', 'content'));

function frontMatter(text) {
	const m = text.match(/^---\n([\s\S]*?)\n---/);
	const fm = {};
	if (!m) return fm;
	for (const line of m[1].split('\n')) {
		const kv = line.match(/^(\w+):\s*(.*?)\s*$/);
		if (kv) fm[kv[1]] = kv[2].replace(/^["']|["']$/g, '');
	}
	return fm;
}

/** [{ label, slugs: ['how-to/draw-a-mesh', ...] }] for a section, or null if no page has a group. */
export function sectionGroups(section) {
	const dir = path.join(CONTENT, section);
	const pages = fs.readdirSync(dir).filter((f) => f.endsWith('.md')).map((f) => {
		const fm = frontMatter(fs.readFileSync(path.join(dir, f), 'utf8'));
		return { slug: `${section}/${f.slice(0, -3)}`, order: fm.order ? Number(fm.order) : 1000, group: fm.group || null,
			title: fm.title || f.slice(0, -3), description: fm.description || '' };
	});
	if (!pages.some((p) => p.group)) return null;
	pages.sort((a, b) => a.order - b.order || a.slug.localeCompare(b.slug));
	let last = null;
	for (const p of pages) {
		if (!p.group) {
			console.warn(`[content-groups] WARNING content/${p.slug}.md: no \`group:\` in the front matter, placed in the group of the previous page (${last})`);
			p.group = last;
		}
		last = p.group;
	}
	const rank = new Map();
	for (const p of pages) rank.set(p.group, Math.min(rank.get(p.group) ?? Infinity, p.order));
	pages.sort((a, b) => rank.get(a.group) - rank.get(b.group) || a.order - b.order || a.slug.localeCompare(b.slug));
	const groups = [];
	for (const p of pages) {
		if (!groups.length || groups.at(-1).label !== p.group) groups.push({ label: p.group, slugs: [], pages: [] });
		groups.at(-1).slugs.push(p.slug);
		groups.at(-1).pages.push(p);
	}
	return groups;
}

/** Starlight sidebar items of a section: one sub-group per `group:`, else autogenerated. */
export function sectionSidebar(section) {
	const groups = sectionGroups(section);
	if (!groups) return [{ autogenerate: { directory: section } }];
	return groups.map((g) => ({ label: g.label, collapsed: false, items: g.slugs.map((slug) => ({ slug })) }));
}
