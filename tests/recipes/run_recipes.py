#!/usr/bin/env python3
"""
Apply the C++ code of every how-to page literally to a fresh copy of the cgp-2027 template
and build it (native, make -j8). A page takes part when its code blocks start with a location
comment such as `// scene.cpp - add at the end of initialize()` (see apply_recipe.py).

Output: build/recipes/<name>/ (one project per recipe), progress printed and written to
build/recipes/recipes.log. Exit code 1 if a recipe fails to apply, to build, or builds with
a warning in src/, or if a line marked "already in the template" is not in it.

Usage:  .venv/bin/python tests/recipes/run_recipes.py [name ...]     (default: every recipe)
Needs:  the native build tools of cgp-2027 (c++, make, GLFW through pkg-config).
"""

import shutil
import subprocess
import sys
import time
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
CGP = (ROOT.parent / "cgp-2027").resolve()
OUT = ROOT / "build" / "recipes"
LOG = OUT / "recipes.log"
APPLY = HERE / "apply_recipe.py"

# Pages whose code blocks are not all applied at once.
#   skip: segment indices (printed by apply_recipe.py) not applied
#   before: pages applied first (a recipe that builds on another one)
#   opengl: the compile definition of the OpenGL version (instead of CGP_OPENGL_3_3): the
#           project is rebuilt from scratch with it (compiled only: may not run on this machine)
SPECIAL = {
    "use-a-newer-opengl-version": {"opengl": "CGP_OPENGL_4_3"},
    "apply-a-texture": {"skip": [3]},                       # step 3, wrap-mode variant below
    "apply-a-texture-wrap": {"page": "how-to/apply-a-texture.md", "skip": [1]},
    "reflect-the-environment": {"before": ["how-to/add-a-skybox.md"]},
}
EXCLUDED = set()


def log(msg):
    line = f"[{time.strftime('%H:%M:%S')}] {msg}"
    print(line, flush=True)
    with open(LOG, "a", encoding="utf-8") as fh:
        fh.write(line + "\n")


def recipes():
    pages = sorted((ROOT / "content" / "how-to").glob("*.md")) + [ROOT / "content/understand/hierarchies.md"]
    out = {}
    for p in pages:
        if p.stem in EXCLUDED or "// scene.cpp - " not in p.read_text() and "// scene.hpp - " not in p.read_text():
            continue
        out[p.stem] = {"page": str(p.relative_to(ROOT / "content"))}
    for name, spec in SPECIAL.items():
        out[name] = {**out.get(name, {}), **spec}
    return out


def run(cmd, cwd=None):
    return subprocess.run(cmd, cwd=cwd, capture_output=True, text=True)


def apply_spec(spec, project):
    """Apply the pages of a recipe spec to project/src/scene.{hpp,cpp}; return the problems."""
    problems = []
    for page, extra in [(p, []) for p in spec.get("before", [])] + \
                       [(spec["page"], ["--skip", ",".join(map(str, spec["skip"]))] if "skip" in spec else [])]:
        r = run([sys.executable, str(APPLY), str(ROOT / "content" / page), str(project)] + extra)
        if r.returncode != 0:
            problems.append(f"apply {page}: " + (r.stderr.strip().splitlines() or ["?"])[-1])
        problems += [f"{page}: {l.strip()}" for l in r.stdout.splitlines() if "WARNING" in l]
    return problems


def write_demo_scene(name, demo_dir):
    """Write demo_dir/scene.{hpp,cpp}: the cgp-2027 template with the code of the page of the
    recipe `name` applied, so that the demo runs exactly the code of the page."""
    import tempfile
    spec = recipes()[name]
    with tempfile.TemporaryDirectory() as tmp:
        (Path(tmp) / "src").mkdir()
        for f in ("scene.hpp", "scene.cpp"):
            shutil.copy(CGP / "src" / f, Path(tmp) / "src" / f)
        problems = apply_spec(spec, Path(tmp))
        if problems:
            raise RuntimeError(f"recipe {name}: " + "; ".join(problems))
        pages = ", ".join(f"content/{p}" for p in spec.get("before", []) + [spec["page"]])
        origin = Path(demo_dir) / "origin.txt"      # origin and license of the assets of the demo
        for f in ("scene.hpp", "scene.cpp"):
            text = (Path(tmp) / "src" / f).read_text()
            head = (f"// Generated by demos/build.py: the cgp-2027 template with the code of {pages}\n"
                    f"// applied (tests/recipes/apply_recipe.py). Do not edit: change the page.\n")
            if f == "scene.cpp" and origin.exists():
                head += "".join(f"// {l}".rstrip() + "\n" for l in origin.read_text().splitlines())
            (Path(demo_dir) / f).write_text(head + text)


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    LOG.write_text("")
    todo = recipes()
    if sys.argv[1:]:
        todo = {k: v for k, v in todo.items() if k in sys.argv[1:]}
    t0 = time.time()

    base = OUT / "base"
    log(f"template {CGP} -> {base} (make -j8)")
    run(["rsync", "-a", "--delete", "--exclude", ".git", "--exclude", "build_*", "--exclude", "project",
         f"{CGP}/", f"{base}/"])
    r = run(["make", "-j8"], cwd=base)
    if r.returncode != 0:
        log("template build FAILED\n" + r.stdout[-2000:] + r.stderr[-2000:])
        return 1

    failures = []
    for k, (name, spec) in enumerate(sorted(todo.items()), 1):
        d = OUT / name
        run(["rsync", "-a", "--delete", f"{base}/", f"{d}/"])
        (d / "project").unlink(missing_ok=True)
        problems = apply_spec(spec, d)
        if not problems and spec.get("opengl"):
            makefile = d / "Makefile"
            makefile.write_text(makefile.read_text().replace("CGP_OPENGL_3_3", spec["opengl"]))
            run(["make", "clean"], cwd=d)
        if not problems:
            r = run(["make", "-j8"], cwd=d)
            text = r.stdout + r.stderr
            warnings = [l for l in text.splitlines() if ("warning:" in l or "error:" in l) and "src/" in l]
            if r.returncode != 0 or not (d / "project").exists():
                problems.append("build failed: " + ("; ".join(warnings[:3]) or text.strip().splitlines()[-1]))
            elif warnings:
                problems.append("warnings: " + "; ".join(warnings[:3]))
        status = "OK" if not problems else "FAILED"
        log(f"({k}/{len(todo)}) {name}: {status}" + "".join(f"\n    {p}" for p in problems))
        if problems:
            failures.append(name)

    log(f"{len(todo) - len(failures)}/{len(todo)} recipes OK in {time.time() - t0:.0f} s"
        + (f"; FAILED: {', '.join(failures)}" if failures else ""))
    return 1 if failures else 0


if __name__ == "__main__":
    sys.exit(main())
